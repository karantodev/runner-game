/**
 * v3.8.50 — Phase 8 Semantic Registry Doc Generator.
 *
 * Reads `ASSET_SEMANTICS` + `getCanonicalSemantic` from
 * `src/config/assetSemantics.js` and writes
 * `docs/asset-semantic-registry.md` — the designer-facing,
 * human-readable view of every world-placeable asset's role,
 * allowed zones, collision type, side-facing rule, support rules,
 * and composition rules.
 *
 * Re-run after any registry edit:
 *   node scripts/generate-semantic-registry.mjs
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs/asset-semantic-registry.md');

const sem = await import(pathToFileURL(path.join(ROOT, 'src/config/assetSemantics.js')).href);

const ROLE_ORDER = sem.listCanonicalRoles();
const ROLE_DESCRIPTIONS = {
  GAMEPLAY_OBSTACLE:    'Spawned ON the road. Player MUST jump / duck / change lane to pass.',
  COLLECTIBLE:          'Pickup the player must hit. Score / heart / rare bonus.',
  BONUS_POWERUP:        'Timed boost on hit. Magnet / shield / 2× / speed-tree / mushroom.',
  ROAD_DECOR:           'Drawn by RoadRenderer (lane tiles, perspective lines). Not a placeable entity.',
  SIDE_DECOR_SMALL:     'Off-road shoulder decor — flowers, grass tufts, small bushes, sprouts.',
  SIDE_DECOR_LARGE:     'Off-road shoulder decor — large trees, big bushes, fence sections, leaf clumps.',
  SIDE_STRUCTURE:       'Shoulder structural prop — wall, brick, pot, pipe, question block. Side-facing.',
  SUPPORT_FOUNDATION:   'Foundation block other props can stack on (grass_dirt_block, walls, step).',
  STACKABLE_TOP:        'Sits on top of a SUPPORT_FOUNDATION (mushroom_red_big, mushroom_blue_big).',
  PLATFORM:             'Floating / hanging platform. Free-floating, can host a child.',
  LANDMARK:             'Single-instance reference object (castle_far, greenhouse_far, player_farmer).',
  BACKGROUND_ONLY:      'Skybox / mountains / clouds / forest_far / meadow_far. Drawn by background pass.',
  UI_ONLY:              'Reserved enum. UI / HUD assets are NOT in this registry.',
  EFFECT_ONLY:          'Reserved enum. Particle / full-screen effect sheets are NOT in this registry.',
};
const ZONE_DESCRIPTIONS = {
  ROAD_CORE:          'The three lanes (-1, 0, +1) the player runs in. Anything here is gameplay.',
  ROAD_EDGE:          'Immediately next to a lane (±1.5 ish). Still in player collision distance.',
  LEFT_SHOULDER:      'Off-road, left of the road. |lane| > 1.5 with negative sign.',
  RIGHT_SHOULDER:     'Off-road, right of the road. |lane| > 1.5 with positive sign.',
  FAR_BACKGROUND:     'Skyline / horizon. Drawn before everything else; no parallax with the road.',
  HUD:                'Reserved. Not used in this catalog yet.',
  FULLSCREEN_EFFECT:  'Reserved. Not used in this catalog yet.',
};
const COLLISION_DESCRIPTIONS = {
  none:                  'No player interaction. Decor / scenery / background.',
  obstacle_jump:         'Player must JUMP over (low obstacle).',
  obstacle_duck:         'Player must DUCK under (overhead obstacle).',
  obstacle_lane_change:  'Player must change lane to avoid (single-lane blocker).',
  collectible:           'Player picks up on contact. Score / heart / rare.',
  powerup:               'Player picks up; activates timed effect.',
  support_only:          'Structural prop. No player contact (always off-road).',
};
const SIDE_FACING_DESCRIPTIONS = {
  neutral:               'Symmetric / mirror-safe. Engine may canvas-flip without lighting issues.',
  left_only:             'Only ever appears on left shoulder. Will never spawn on right.',
  right_only:            'Only ever appears on right shoulder.',
  pair_required:         '_left.png and _right.png both required. Engine must NOT mirror-flip.',
  road_facing_required:  'Pair required AND the lit / detailed face MUST point toward the road.',
};

function fmtBool(b) { return b ? '✓' : '·'; }
function fmtArr(arr) { return arr.length ? arr.join(', ') : '—'; }
function fmtSupport(r) {
  return [
    `canStandAlone:${fmtBool(r.canStandAlone)}`,
    `requiresGround:${fmtBool(r.requiresGround)}`,
    `requiresPlatform:${fmtBool(r.requiresPlatform)}`,
    `canStackOn:${fmtBool(r.canStackOn)}`,
    `canSupport:${fmtBool(r.canSupport)}`,
    `maxStackHeight:${r.maxStackHeight}`,
  ].join(' · ');
}
function fmtComp(r) {
  return [
    `minSpacingSameType:${r.minSpacingSameType}`,
    `maxPerScreen:${r.maxPerScreen}`,
    `densityWeight:${r.densityWeight}`,
    `canOverlapDecor:${fmtBool(r.canOverlapDecor)}`,
    `blocksRoadReadability:${fmtBool(r.blocksRoadReadability)}`,
  ].join(' · ');
}

const lines = [];
lines.push('# Asset Semantic Registry');
lines.push('');
lines.push(`Auto-generated by \`scripts/generate-semantic-registry.mjs\`. Regenerate after editing \`src/config/assetSemantics.js\`. Last run ${new Date().toISOString()}.`);
lines.push('');
lines.push('Single source of truth for every world-placeable asset: where it may spawn, whether it can touch the road, whether it needs support, whether it is side-aware, whether it can stack with other assets.');
lines.push('');
lines.push('**Scope.** World scene / gameplay assets only. UI panels, HUD icons, particle sheets, and full-screen effects are out of scope — they have their own consumers and don\'t need placement rules.');
lines.push('');

// ── Enum reference sections ───────────────────────────────────────────
lines.push('## Canonical role enum');
lines.push('');
lines.push('| Role | What it is |');
lines.push('|---|---|');
for (const r of ROLE_ORDER) {
  lines.push(`| \`${r}\` | ${ROLE_DESCRIPTIONS[r] ?? '—'} |`);
}
lines.push('');

lines.push('## Canonical zone enum');
lines.push('');
lines.push('| Zone | Where it is |');
lines.push('|---|---|');
for (const z of sem.listCanonicalZones()) {
  lines.push(`| \`${z}\` | ${ZONE_DESCRIPTIONS[z] ?? '—'} |`);
}
lines.push('');

lines.push('## Gameplay-collision enum');
lines.push('');
lines.push('| Value | Player action |');
lines.push('|---|---|');
for (const c of ['none', 'obstacle_jump', 'obstacle_duck', 'obstacle_lane_change', 'collectible', 'powerup', 'support_only']) {
  lines.push(`| \`${c}\` | ${COLLISION_DESCRIPTIONS[c]} |`);
}
lines.push('');

lines.push('## Side-facing enum');
lines.push('');
lines.push('| Value | Engine contract |');
lines.push('|---|---|');
for (const s of ['neutral', 'left_only', 'right_only', 'pair_required', 'road_facing_required']) {
  lines.push(`| \`${s}\` | ${SIDE_FACING_DESCRIPTIONS[s]} |`);
}
lines.push('');

// ── Per-asset registry, grouped by role ───────────────────────────────
lines.push('## Active asset registry');
lines.push('');

const byRole = new Map();
for (const key of sem.listSemanticKeys()) {
  const c = sem.getCanonicalSemantic(key);
  if (!c) continue;
  if (!byRole.has(c.role)) byRole.set(c.role, []);
  byRole.get(c.role).push(c);
}

for (const role of ROLE_ORDER) {
  const entries = byRole.get(role);
  if (!entries?.length) continue;
  lines.push(`### ${role} (${entries.length})`);
  lines.push('');
  lines.push('| Asset | Allowed zones | Collision | Side facing | Support rules | Composition rules |');
  lines.push('|---|---|---|---|---|---|');
  entries.sort((a, b) => a.key.localeCompare(b.key));
  for (const c of entries) {
    lines.push(`| \`${c.key}\` | ${fmtArr(c.allowedZones)} | \`${c.gameplayCollision}\` | \`${c.sideFacing}\` | ${fmtSupport(c.supportRules)} | ${fmtComp(c.compositionRules)} |`);
  }
  lines.push('');
}

lines.push('## Out of scope (intentional)');
lines.push('');
lines.push('| Category | Why excluded |');
lines.push('|---|---|');
lines.push('| UI / HUD panels & icons | Consumed by HUD renderer, not the world generator. |');
lines.push('| Particle / effect sheets | Consumed by EffectsRenderer; no placement rules apply. |');
lines.push('| Full-screen effects | Consumed by per-frame composite layer; not entity-driven. |');
lines.push('| Player sprite frames | Single entity, animation-driven. Covered by player frame audit. |');
lines.push('');

lines.push('## Companion artifacts');
lines.push('');
lines.push('- `docs/asset-production-manifest.md` — bucket / per-asset usage inventory.');
lines.push('- `docs/composition-validation-report.md` — generated by `scripts/validate-composition.mjs`. Lists current hard violations + warnings.');
lines.push('- `docs/asset-contact-sheets/*` — visual inventory cards (now showing role / zone / side-facing).');
lines.push('- `scripts/audit-assets.mjs` — semantic-coverage strict audit (CI gate).');

await fs.writeFile(OUT, lines.join('\n'));
console.log(`[generate-semantic-registry] wrote ${path.relative(ROOT, OUT)} (${sem.listSemanticKeys().length} active assets)`);
